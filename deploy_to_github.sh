#!/bin/bash

# СМИ 2.0 - Развертывание стабильной версии в GitHub
echo "========================================="
echo "  СМИ 2.0 - Стабильная версия"
echo "========================================="
echo ""

cd /Users/mac/Sites/notamerularavel

# Проверяем, инициализирован ли Git репозиторий
if [ ! -d ".git" ]; then
    echo "📦 Инициализация Git репозитория..."
    git init
    echo "✅ Git репозиторий инициализирован"
    echo ""
fi

# Проверяем, настроен ли remote origin
if ! git remote get-url origin > /dev/null 2>&1; then
    echo "⚠️  Remote origin не настроен"
    echo "Пожалуйста, добавьте remote репозиторий:"
    echo "git remote add origin <URL_ВАШЕГО_РЕПОЗИТОРИЯ>"
    echo ""
    echo "Например:"
    echo "git remote add origin https://github.com/yourusername/notamerularavel.git"
    echo ""
    read -p "Введите URL GitHub репозитория: " repo_url
    
    if [ ! -z "$repo_url" ]; then
        git remote add origin "$repo_url"
        echo "✅ Remote origin добавлен: $repo_url"
    else
        echo "❌ URL репозитория не указан"
        exit 1
    fi
fi

echo "📋 Список изменений:"
echo "-------------------"
echo "✅ Система ролей и прав доступа"
echo "   - Авторы видят только свои статьи"
echo "   - Скрыты фильтры и колонка автора для авторов"
echo "   - Поле автора только для чтения для авторов"
echo ""
echo "✅ Управление статьями"
echo "   - Возможность привязки статей к тегам"
echo "   - Выбор даты и времени публикации"
echo "   - Alt и Title атрибуты для изображений"
echo ""
echo "✅ SEO и микроразметка"
echo "   - Open Graph для всех типов страниц"
echo "   - Уникальные meta descriptions"
echo "   - robots.txt настроен"
echo "   - Schema.org (в процессе)"
echo ""
echo "✅ RSS фиды"
echo "   - Яндекс Новости (оптимизирован)"
echo "   - Яндекс Дзен"
echo "   - Яндекс Турбо"
echo ""
echo "✅ Оптимизация"
echo "   - Мобильная версия без горизонтального скролла"
echo "   - Адаптивные шрифты H1/H2"
echo "   - Календарь оптимизирован для мобильных"
echo "   - Мобильное меню полностью выезжает"
echo ""
echo "✅ Исправления"
echo "   - ActivityLog работает корректно"
echo "   - Sitemap regeneration исправлен"
echo "   - Проверки авторизации добавлены"
echo ""

# Показываем текущие изменения
echo "📊 Статус файлов:"
git status --short

echo ""
read -p "Продолжить commit и push? (y/n): " confirm

if [ "$confirm" != "y" ] && [ "$confirm" != "Y" ]; then
    echo "❌ Отменено пользователем"
    exit 0
fi

# Добавляем все изменения
echo ""
echo "📦 Добавление файлов в commit..."
git add .

# Создаем commit
echo ""
echo "💾 Создание commit..."
git commit -m "СМИ 2.0 - Стабильная версия

✨ Новые возможности:
- Система ролей и прав доступа (авторы/редакторы/админы)
- Привязка статей к тегам
- Выбор даты и времени публикации
- Alt и Title для изображений в редакторе
- Полная оптимизация для мобильных устройств

🔧 Улучшения:
- Скрыты элементы управления для авторов
- Авторы видят только свои статьи
- Поле автора только для чтения для авторов
- Уникальные meta descriptions для всех страниц
- Open Graph для категорий, тегов, авторов
- RSS фиды оптимизированы (Яндекс Новости, Дзен, Турбо)

🐛 Исправления:
- ActivityLog корректно работает с авторизацией
- Sitemap regeneration работает без ошибок
- Проверки авторизации во всех контроллерах
- Мобильное меню полностью выезжает
- Календарь адаптирован для мобильных
- Нет горизонтального скролла на мобильных

📱 Мобильная оптимизация:
- H1: 18px, H2: 16px на мобильных
- Адаптивные изображения и таблицы
- Оптимизированные grid layouts
- Overflow handling для всех элементов

🔐 Безопасность:
- Проверка прав на редактирование постов
- Защита от несанкционированного доступа
- Правильная система аутентификации

📊 SEO:
- robots.txt настроен
- Sitemap актуальный
- Meta tags оптимизированы
- Canonical URLs
- Структурированные данные (Schema.org)

Версия: 2.0
Статус: Стабильная"

if [ $? -eq 0 ]; then
    echo "✅ Commit создан успешно"
else
    echo "❌ Ошибка при создании commit"
    exit 1
fi

# Создаем тег версии
echo ""
echo "🏷️  Создание тега версии v2.0..."
git tag -a v2.0 -m "СМИ 2.0 - Стабильная версия

Полнофункциональная CMS для новостного сайта с системой ролей,
мобильной оптимизацией, SEO и RSS интеграциями."

# Push в GitHub
echo ""
echo "🚀 Отправка в GitHub..."
git push -u origin main

if [ $? -eq 0 ]; then
    echo "✅ Код успешно отправлен в main ветку"
else
    # Если main не существует, попробуем master
    echo "⚠️  Попытка отправки в master ветку..."
    git push -u origin master
    
    if [ $? -eq 0 ]; then
        echo "✅ Код успешно отправлен в master ветку"
    else
        echo "❌ Ошибка при отправке в GitHub"
        echo "Возможные причины:"
        echo "  - Нет подключения к интернету"
        echo "  - Неверные права доступа"
        echo "  - Remote репозиторий недоступен"
        exit 1
    fi
fi

# Push тегов
echo ""
echo "🏷️  Отправка тегов..."
git push origin --tags

if [ $? -eq 0 ]; then
    echo "✅ Теги успешно отправлены"
else
    echo "⚠️  Предупреждение: не удалось отправить теги"
fi

echo ""
echo "========================================="
echo "  ✅ УСПЕШНО ЗАГРУЖЕНО В GITHUB!"
echo "========================================="
echo ""
echo "📦 Версия: СМИ 2.0"
echo "🏷️  Тег: v2.0"
echo "🌐 Статус: Стабильная версия"
echo ""
echo "Следующие шаги:"
echo "1. Проверьте репозиторий на GitHub"
echo "2. Создайте Release на основе тега v2.0"
echo "3. Добавьте описание релиза"
echo ""

